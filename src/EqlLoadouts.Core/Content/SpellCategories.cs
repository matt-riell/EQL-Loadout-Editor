    public static string Name(int id) => (uint)id < (uint)Names.Length ? Names[id] : string.Empty;

    public static string DamageName(int id) => (uint)id < (uint)Damage.Length && Damage[id] ? Names[id] : string.Empty;

    private static bool[] BuildDamage()
    {
        var flags = new bool[Names.Length];
        foreach (var id in new[] { 14, 29, 38, 58, 72, 75, 135, 137, 138 })
        {
            flags[id] = true;
        }

        return flags;
    }

